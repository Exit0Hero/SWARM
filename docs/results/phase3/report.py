"""Render the tables (and, if matplotlib is installed, the figures) for a Phase 3 study.

Reads only the analysis JSON written by ``swarm.experiments.study_analysis``; it never runs
episodes. Usage (from the repository root)::

    python docs/results/phase3/report.py --analysis docs/results/phase3/analysis.json \\
        --out docs/results/phase3/results.md --plots docs/results/phase3/figures

Figures need the optional ``viz`` extra (``pip install -e .[viz]``).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

SWEEP_POLICIES = ("frontier", "frontier_shared", "auction_comm", "auction_no_reassign")
COLORS = {  # categorical slots 1-4 of the dataviz reference palette (validated)
    "frontier": "#2a78d6",
    "frontier_shared": "#eb6834",
    "auction_comm": "#1baf7a",
    "auction_no_reassign": "#eda100",
}
MARKERS = {"frontier": "o", "frontier_shared": "s", "auction_comm": "^", "auction_no_reassign": "D"}
SWEEPS = {
    "Communication range (drone, ground)": [
        ("range_short", "4, 3"),
        ("nominal", "8, 5"),
        ("range_long", "16, 10"),
        ("range_unlimited", "unlimited"),
    ],
    "Packet loss p_drop": [
        ("nominal", "0"),
        ("drop_10", "0.1"),
        ("drop_30", "0.3"),
        ("drop_60", "0.6"),
    ],
    "Latency, jitter (steps)": [("nominal", "0, 0"), ("delay_2_1", "2, 1"), ("delay_5_3", "5, 3")],
    "Bandwidth (units/agent/step)": [("nominal", "unlimited"), ("bw_32", "32"), ("bw_16", "16")],
}
ORACLE = "assignment_oracle"


def _fmt(x: float | None, digits: int = 1) -> str:
    return "—" if x is None else f"{x:.{digits}f}"


def _ci(m: dict[str, Any] | None, digits: int = 1) -> str:
    if not m or m.get("mean") is None:
        return "—"
    if m.get("ci_low") is None:
        return _fmt(m["mean"], digits)
    return f"{m['mean']:.{digits}f} [{m['ci_low']:.{digits}f}, {m['ci_high']:.{digits}f}]"


def _label(policy: str) -> str:
    if policy == ORACLE:
        return f"{policy} (ORACLE, reference)"
    if policy == "assignment":
        return "assignment (pooled, perfect comms)"
    return policy


def render(analysis: dict[str, Any]) -> str:
    s = analysis["summaries"]
    conditions: list[str] = []
    for v in s.values():
        if v["condition"] not in conditions:
            conditions.append(v["condition"])
    out = [
        f"# {analysis['study']} results",
        "",
        f"Seeds {analysis['seeds'][0]}-{analysis['seeds'][-1]} (n = {len(analysis['seeds'])} "
        f"per cell, {analysis['designation']}). Generated by `report.py` from `analysis.json`.",
        "Intervals are 95% percentile bootstrap. Differences are B - A, paired by seed.",
        "",
        "## Confirmatory hypotheses (Holm-adjusted)",
        "",
        "| ID | A → B | Metric | Mean A | Mean B | Diff [95% CI] | d_z | p | p (Holm) | Verdict |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in analysis["confirmatory"]:
        out.append(
            f"| {r['id']} | {r['a'][0]}/{r['a'][1]} → {r['b'][0]}/{r['b'][1]} | {r['metric']} "
            f"({r['expected']}) | {_fmt(r['mean_a'], 2)} | {_fmt(r['mean_b'], 2)} | "
            f"{_fmt(r['mean_difference'], 2)} [{_fmt(r['ci_low'], 2)}, {_fmt(r['ci_high'], 2)}] | "
            f"{_fmt(r['cohens_dz'], 2)} | {r['p_value']:.4f} | {r['p_adjusted']:.4f} | "
            f"{r['verdict']} |"
        )
    out += [
        "",
        "## Search time (`time_censored`, steps; lower is faster)",
        "",
        "| Condition | Policy | time_censored | mission_success | recall | injected failures |",
        "|---|---|---|---|---|---|",
    ]
    for v in s.values():
        m = v["metrics"]
        out.append(
            f"| {v['condition']} | {_label(v['policy'])} | {_ci(m.get('time_censored'))} | "
            f"{_ci(m.get('mission_success'), 2)} | {_ci(m.get('recall'), 3)} | "
            f"{_fmt((m.get('agents_disabled_injected') or {}).get('mean'), 2)} |"
        )
    out += [
        "",
        "## Communication (channel policies)",
        "",
        "| Condition | Policy | units/step | delivery rate | survivor-info delay (steps) |"
        " informed fraction |",
        "|---|---|---|---|---|---|",
    ]
    for v in s.values():
        m = v["metrics"]
        if not (m.get("messages_sent") or {}).get("mean"):
            continue
        out.append(
            f"| {v['condition']} | {v['policy']} | {_ci(m.get('message_units_per_step'))} | "
            f"{_ci(m.get('message_delivery_rate'), 3)} | "
            f"{_ci(m.get('survivor_info_delay_mean'))} | "
            f"{_ci(m.get('survivor_info_informed_fraction'), 2)} |"
        )
    out += [
        "",
        "## Failure detection and reassignment (auction policies)",
        "",
        "Means per episode; delays only over pairs or sectors where they are defined.",
        "",
        "| Condition | Policy | disabled-detection delay | suspicion delay | false suspicions |"
        " abandoned | reassignment delay | unresolved sectors | duplicate-ownership steps |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for v in s.values():
        m = v["metrics"]
        if (m.get("false_suspicions") or {}).get("mean") is None:
            continue
        cells = [
            _fmt((m.get(k) or {}).get("mean"), 2)
            for k in (
                "disabled_detection_delay_mean",
                "suspicion_detection_delay_mean",
                "false_suspicions",
                "abandoned_sectors",
                "reassignment_delay_mean",
                "unresolved_sectors",
                "duplicate_ownership_steps",
            )
        ]
        out.append(f"| {v['condition']} | {v['policy']} | " + " | ".join(cells) + " |")
    sig = [
        r for r in analysis["exploratory"] if (r.get("p_adjusted_bh") or 1.0) < analysis["alpha"]
    ]
    out += [
        "",
        f"## Exploratory comparisons with BH-adjusted q < {analysis['alpha']} "
        f"({len(sig)} of {len(analysis['exploratory'])})",
        "",
        "Descriptive only. The full list is in `analysis.json`.",
        "",
        "| Kind | A → B | Metric | Diff [95% CI] | d_z | q (BH) |",
        "|---|---|---|---|---|---|",
    ]
    for r in sig:
        out.append(
            f"| {r['kind']} | {r['a'][0]}/{r['a'][1]} → {r['b'][0]}/{r['b'][1]} | {r['metric']} | "
            f"{_fmt(r['mean_difference'], 3)} [{_fmt(r['ci_low'], 3)}, {_fmt(r['ci_high'], 3)}] | "
            f"{_fmt(r['cohens_dz'], 2)} | {r['p_adjusted_bh']:.4f} |"
        )
    out += ["", "## Runtime (wall clock, single process; not deterministic)", ""]
    times = [
        v["metrics"]["runtime_seconds_per_episode"]["mean"]
        for v in s.values()
        if "runtime_seconds_per_episode" in v["metrics"]
    ]
    out.append(
        f"Mean seconds per episode across cells: {min(times):.3f} to {max(times):.3f} "
        f"(median {sorted(times)[len(times) // 2]:.3f})."
    )
    return "\n".join(out) + "\n"


def plot(analysis: dict[str, Any], directory: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    directory.mkdir(parents=True, exist_ok=True)
    s = analysis["summaries"]
    written: list[Path] = []
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})

    nominal = [v for v in s.values() if v["condition"] == "nominal"]
    if nominal:
        nominal.sort(key=lambda v: v["metrics"]["time_censored"]["mean"])
        fig, ax = plt.subplots(figsize=(6.4, 0.42 * len(nominal) + 1.0))
        for k, v in enumerate(nominal):
            m = v["metrics"]["time_censored"]
            color = "#8a8985" if v["policy"] == ORACLE else "#2a78d6"
            ax.plot([m["ci_low"], m["ci_high"]], [k, k], color=color, lw=2)
            ax.plot(m["mean"], k, "o", color=color, ms=7)
            ax.annotate(
                f"{m['mean']:.1f}",
                (m["ci_high"], k),
                xytext=(5, -3),
                textcoords="offset points",
                color="#52514e",
            )
        ax.set_yticks(range(len(nominal)), [_label(v["policy"]) for v in nominal])
        ax.set_xlabel("time_censored (steps to recall target; 201 = not reached)")
        fig.suptitle("Nominal condition: search time, mean and 95% CI (n = 50)", x=0.01, ha="left")
        ax.grid(axis="x", color="#e4e3df", lw=0.8)
        fig.tight_layout()
        path = directory / "nominal_policies.png"
        fig.savefig(path, dpi=150)
        plt.close(fig)
        written.append(path)

    available = {v["condition"] for v in s.values()}
    sweeps = {k: lv for k, lv in SWEEPS.items() if all(c in available for c, _ in lv)}
    if sweeps:
        fig, axes = plt.subplots(2, 2, figsize=(9, 6.4), sharey=True)
        for ax, (title, levels) in zip(axes.flat, sweeps.items(), strict=False):
            for policy in SWEEP_POLICIES:
                ms = [s[f"{c}/{policy}"]["metrics"]["time_censored"] for c, _ in levels]
                xs = range(len(levels))
                ax.fill_between(
                    xs,
                    [m["ci_low"] for m in ms],
                    [m["ci_high"] for m in ms],
                    color=COLORS[policy],
                    alpha=0.12,
                    lw=0,
                )
                ax.plot(
                    xs,
                    [m["mean"] for m in ms],
                    color=COLORS[policy],
                    lw=2,
                    marker=MARKERS[policy],
                    ms=8,
                    label=policy,
                )
            ax.set_xticks(range(len(levels)), [lab for _, lab in levels])
            ax.set_title(title, loc="left")
            ax.grid(axis="y", color="#e4e3df", lw=0.8)
        for ax in axes[:, 0]:
            ax.set_ylabel("time_censored (steps)")
        handles, labels = axes[0, 0].get_legend_handles_labels()
        fig.legend(handles, labels, frameon=False, loc="lower center", ncol=4)
        fig.suptitle(
            "One-factor channel sweeps (mean, 95% CI band; n = 50 per point)", x=0.01, ha="left"
        )
        fig.tight_layout(rect=(0, 0.05, 1, 1))
        path = directory / "channel_sweeps.png"
        fig.savefig(path, dpi=150)
        plt.close(fig)
        written.append(path)
    return written


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--plots", type=Path)
    args = parser.parse_args()
    analysis = json.loads(args.analysis.read_text(encoding="utf-8"))
    args.out.write_text(render(analysis), encoding="utf-8")
    if args.plots is not None:
        try:
            for path in plot(analysis, args.plots):
                print(path)
        except ImportError:
            print("matplotlib not installed; figures skipped (pip install -e .[viz])")


if __name__ == "__main__":
    main()
